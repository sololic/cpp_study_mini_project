#include <iostream>

// 포인터(pointer) 기초
void ptr_basic() {
    int a = 10;
    int* ptr = &a;  // ptr은 a의 주소를 저장하는 포인터
    std::cout << "[포인터 기본]\n";
    std::cout << "a = " << a << ", ptr = " << ptr << ", *ptr = " << *ptr << "\n\n";
    *ptr = 99;      // ptr이 가리키는 값을 바꾸면 a도 바뀜
    std::cout << "ptr이 가리키는 값 = 99 대입 후, a = " << a << "\n\n";
    std::cout << "a = " << a << ", ptr = " << ptr << ", *ptr = " << *ptr << "\n\n";
    int b = 100;
    ptr = &b;       // ptr이 이제 b의 주소를 가리킴
    std::cout << "ptr이 b의 주소를 가리키도록 변경 후, ptr = " << ptr << ", *ptr = " << *ptr << "\n\n";
    /*
        **결론**
        포인터는 주소를 저장하는 변수이므로, 포인터가 가리키는 대상을 바꿀 수 있다. 
        반면 참조는 변수의 별명으로, 참조가 한 번 특정 변수를 가리키면 다른 변수로 바꿀 수 없다. 
        why? -> 참조는 선언과 동시에 초기화되어야 하고, 그 이후에는 다른 대상을 참조할 수 없도록 설계되어 있기 때문이다.

        ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
        포인터 vs 참조 — 가리키는 대상 변경 여부
        ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━       
        ■ 결론
        포인터 → 가리키는 대상 변경 가능
        참조   → 가리키는 대상 변경 불가
        ■ 이유
        포인터는 주소를 저장하는 변수 → 가리키는 대상 변경 가능
        참조는 변수의 별명 → 선언과 동시에 초기화, 이후 다른 대상을 참조할 수 없도록 설계

        val = 집 (물건 + 주소 둘 다 가짐)
        val 안의 값(42) = 물건
        &val = 집 주소를 가져오는 연산자
        ptr = 주소가 적힌 메모지
        *ptr = 메모지의 주소로 찾아가서 물건을 꺼냄 (역참조)

        int val = 42;   // 집(val), 물건(42)
        &val            // 집 주소 가져오기
        int* ptr = &val // 메모지에 집 주소 적기
        *ptr            // 메모지 보고 집 찾아가서 물건 꺼내기
    */
}

void ptr_const() {
    int a = 10;
    const int* ptr = &a;  // ptr은 a의 주소를 저장하는 포인터, 하지만 ptr이 가리키는 값을 변경할 수 없음
    std::cout << "[const 포인터]\n";
    std::cout << "a = " << a << ", ptr = " << ptr << ", *ptr = " << *ptr << "\n\n";
    // *ptr = 99;      // 컴파일 에러! ptr이 가리키는 값을 변경할 수 없음
    std::cout << "ptr이 가리키는 값 = 99 대입 시도 컴파일 에러 발생\n\n";
    std::cout << "a = " << a << ", ptr = " << ptr << ", *ptr = " << *ptr << "\n\n";
    int b = 100;
    ptr = &b;       // ptr이 이제 b의 주소를 가리킴
    std::cout << "ptr이 b의 주소를 가리키도록 변경 후, ptr = " << ptr << ", *ptr = " << *ptr << "\n\n";
    
    /*
        **결론**
        const int* ptr은 "ptr이 가리키는 값을 변경할 수 없다"는 의미이므로, 
        ptr이 가리키는 대상을 바꿀 수는 있지만, ptr이 가리키는 주소의 값을 바꿀 수는 없다. 

        반면 int* const ptr은 "ptr 자체가 가리키는 대상을 변경할 수 없다"는 의미이므로, 
        ptr이 가리키는 대상을 바꿀 수는 없지만, ptr이 가리키는 주소의 값을 바꿀 수 있다. 
        why? -> const의 위치에 따라 의미가 달라지기 때문이다. 

        const int* ptr → ptr이 가리키는 값을 변경할 수 없음 (ptr이 가리키는 대상은 변경 가능)
        int* const ptr → ptr 자체가 가리키는 대상을 변경할 수 없음 (ptr이 가리키는 대상은 변경 불가)
        => 쉽게 생각하면 const 다음에 오는 것은 "변경할 수 없는 것"이 된다.
    */      
}

int main() {
    // ptr_basic();
    ptr_const();
    // return 0;
}